#!/usr/bin/env node
/**
 * Copy the syllable rule to the browser.
 *
 *   node scripts/sync-syllables.js
 *
 * The browser needs the rule so a long word turns red BEFORE it is sent, and
 * caveman-syllable-check.js compares the two files byte for byte because silent
 * drift means the warning light says green while the server charges a point —
 * which reads to the player as the game cheating.
 *
 * That check was written with "re-copy it across keeping the frontend header"
 * as the fix, i.e. a manual step. A manual step in the middle of a guard is a
 * guard people learn to route around, so here it is as one command.
 *
 * The server copy is the source of truth. This only ever writes the browser one.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const SERVER = path.join(here, '..', 'src', 'games', 'cavemanclues', 'syllables.js');
const BROWSER = path.join(here, '..', '..', 'frontend', 'src', 'lib', 'syllables.js');

const HEADER = `/*
  A VERBATIM COPY of backend/src/games/cavemanclues/syllables.js.

  The browser needs it so a Clue Giver sees a long word turn red BEFORE they
  send it, rather than only after it has cost them a point. The server keeps the
  authoritative copy — the client's is a warning light and nothing more.

  DO NOT EDIT THIS FILE. Edit the server copy and run:

      cd backend && npm run sync:syllables

  Two copies of one rule drift, and this pair would drift SILENTLY: the warning
  light would go green while the server still charged a point, which reads to
  the player as the game cheating. backend/scripts/caveman-syllable-check.js
  compares the two byte for byte below this header and fails if they differ.
*/

`;

if (!fs.existsSync(BROWSER)) {
  console.error(`No browser copy at ${BROWSER} — nothing to sync.`);
  process.exit(1);
}

const server = fs.readFileSync(SERVER, 'utf8');
const before = fs.readFileSync(BROWSER, 'utf8');
const after = HEADER + server;

if (before === after) {
  console.log('syllable rule — the browser copy already matches the server copy');
  process.exit(0);
}

fs.writeFileSync(BROWSER, after);
console.log('syllable rule — browser copy updated from the server copy');
console.log(`  ${BROWSER}`);
